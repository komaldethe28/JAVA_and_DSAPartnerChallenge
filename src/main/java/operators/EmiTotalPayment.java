//Q18: A person pays EMI every month. Find total payment after N months.

class EmiTotalPayment {
    public static void main(String[] args) {
        double EMI=2000;
        int noOfMonths=12;
        double totalEMI=EMI*noOfMonths;
        System.out.println("Total EMI after 12 months :"+totalEMI);
    }
}